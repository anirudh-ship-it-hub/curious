// Curious — app-shell service worker.
// Deliberately minimal: only ever caches static, content-hashed Next.js build assets
// (cache-first, safe since the filename changes whenever the content does) and falls back to a
// cached page only when a navigation genuinely fails offline (network-first otherwise). Never
// caches /api/* — those calls carry auth state and live data (recommendations, saved items,
// the AI pipeline), and serving a stale response there would be a real correctness bug, not a
// convenience. Bump CACHE_NAME to invalidate everything on the next deploy.
const CACHE_NAME = "curious-shell-v1";

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/")) return;

  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((response) => {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
            return response;
          })
      )
    );
    return;
  }

  event.respondWith(
    fetch(request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      })
      .catch(() => caches.match(request))
  );
});
